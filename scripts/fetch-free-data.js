const fs = require('fs');
const path = require('path');

const API_URL = 'https://fakestoreapi.com/products';
const PRODUCTS_FILE = path.join(__dirname, '../data/products.js');

const processProducts = async () => {
  console.log('Fetching products from FakeStoreAPI...');
  
  try {
    const response = await fetch(API_URL);
    const rawProducts = await response.json();
    
    console.log(`Found ${rawProducts.length} products. Processing...`);
    const formattedProducts = [];
    
    for (const p of rawProducts) {
      const slug = p.title.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      
      formattedProducts.push({
        id: p.id,
        name: p.title,
        slug: slug,
        brand: 'OpenSource',
        short_description: p.description.substring(0, 50) + '...',
        description: p.description,
        price: p.price.toString(),
        regular_price: (p.price * 1.2).toFixed(2).toString(),
        sale_price: p.price.toString(),
        on_sale: true,
        average_rating: p.rating.rate.toString(),
        rating_count: p.rating.count,
        categories: [{ id: p.category, name: p.category.charAt(0).toUpperCase() + p.category.slice(1), slug: p.category }],
        tags: [p.category],
        images: [{ id: 1, src: p.image, alt: p.title }],
        attributes: [],
        stock_status: 'instock',
        badge: 'Sale',
      });
    }
    
    const fileContent = `/* Generated by scraping script from FakeStoreAPI */\n\nexport const products = ${JSON.stringify(formattedProducts, null, 2)};\n\nexport function getProductBySlug(slug) {\n  return products.find((p) => p.slug === slug) || null;\n}\n\nexport function getProductsByCategory(categorySlug) {\n  return products.filter((p) =>\n    p.categories.some((c) => c.slug === categorySlug)\n  );\n}\n\nexport function getProductsByTag(tagName) {\n  return products.filter((p) =>\n    p.tags.some((t) => typeof t === 'object' ? t.name === tagName : t === tagName)\n  );\n}\n\nexport function searchProducts(query) {\n  const q = query.toLowerCase();\n  return products.filter(\n    (p) =>\n      p.name.toLowerCase().includes(q) ||\n      p.brand.toLowerCase().includes(q) ||\n      p.short_description.toLowerCase().includes(q) ||\n      p.categories.some((c) => c.name.toLowerCase().includes(q))\n  );\n}\n\nexport function formatPrice(price) {\n  return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(Number(price));\n}\n\nexport function getDiscountPercentage(regularPrice, salePrice) {\n  if (!salePrice || !regularPrice) return 0;\n  return Math.round(((regularPrice - salePrice) / regularPrice) * 100);\n}\n`;

    fs.writeFileSync(PRODUCTS_FILE, fileContent);
    console.log(`Successfully fetched ${formattedProducts.length} products and saved to data/products.js!`);
  } catch (err) {
    console.error('Error fetching products:', err);
  }
};

processProducts();
